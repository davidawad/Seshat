import { useEffect, useMemo, useState } from 'react'
import { splitMath } from '../lib/math/split'
import './math-text.css'

const Formula = ({ tex, display }: { readonly tex: string; readonly display: boolean }) => {
  const [svg, setSvg] = useState<string | null>(null)

  useEffect(() => {
    let live = true
    void import('../lib/math/render').then(async ({ typesetTex }) => {
      const markup = await typesetTex(tex, display)
      if (live) setSvg(markup)
    })
    return () => {
      live = false
    }
  }, [tex, display])

  const className = display ? 'math math-display' : 'math'
  // Until MathJax has loaded (or if the TeX cannot be typeset) the formula shows as its source.
  if (svg === null || svg === '') return <span className={`${className} math-source`}>{tex}</span>
  // The markup is generated by MathJax from the TeX source (no html/require packages), never taken from the card.
  return <span className={className} role="img" aria-label={tex} dangerouslySetInnerHTML={{ __html: svg }} />
}

/**
 * Card text with LaTeX typeset by MathJax: `$x^2$` and `\(x^2\)` inline, `$$..$$` and `\[..\]` as display math.
 * Text without a formula renders as itself and never loads MathJax.
 */
export const MathText = ({ text }: { readonly text: string }) => {
  const segments = useMemo(() => splitMath(text), [text])
  if (!segments.some((segment) => segment.kind === 'math')) return <>{text}</>
  return (
    <>
      {segments.map((segment, index) =>
        segment.kind === 'text' ? (
          <span key={index}>{segment.text}</span>
        ) : (
          <Formula key={index} tex={segment.tex} display={segment.display} />
        ),
      )}
    </>
  )
}
